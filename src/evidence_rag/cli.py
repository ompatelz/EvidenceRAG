"""JSON command-line interface to the provider-free local SDK."""

import argparse
import json
import sys
from importlib.resources import files
from pathlib import Path

import pymupdf
from pydantic import BaseModel, ValidationError

from evidence_rag import __version__
from evidence_rag.answers import DraftAnswer
from evidence_rag.calculations import CalculationError, CalculationRequest
from evidence_rag.documents import DocumentIngestionResponse, IngestionState, IntakeError
from evidence_rag.documents.storage import ArtifactNotFoundError, StorageError
from evidence_rag.recipes import CalculationRecipe
from evidence_rag.sdk import (
    CollectionDraftRequest,
    CollectionSearchRequest,
    DocumentRef,
    EvidenceRAG,
    SearchRequest,
)


def export_skill(destination: Path) -> Path:
    """Export the bundled skill to a new directory; never overwrite an installation."""
    source = files("evidence_rag").joinpath("evidence-rag-agent")
    destination.mkdir(parents=True, exist_ok=False)
    for relative in ("SKILL.md", "agents/openai.yaml", "references/tools.md"):
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(source.joinpath(relative).read_bytes())
    return destination


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(prog="evidence-rag")
    result.add_argument("--version", action="version", version=__version__)
    result.add_argument("--artifact-root", type=Path, default=None)
    commands = result.add_subparsers(dest="command", required=True)
    ingest = commands.add_parser("ingest", help="Ingest an explicitly selected local PDF")
    ingest.add_argument("path", type=Path)
    catalog = commands.add_parser("documents", help="List this store's ingested versions")
    catalog.add_argument("--offset", type=int, default=0)
    catalog.add_argument("--limit", type=int, default=20)
    commands.add_parser("doctor", help="Check local setup without downloading models")
    for name in ("search-collection", "check-collection"):
        collection = commands.add_parser(name)
        collection.add_argument("--request", type=Path, required=True)
    for name in (
        "search",
        "evidence",
        "check",
        "retry",
        "status",
        "page",
        "calculate",
        "explain",
        "context",
        "recipe",
        "visual",
    ):
        command = commands.add_parser(name)
        command.add_argument("--document-id", required=True)
        command.add_argument("--sha256", required=True)
        if name in ("search", "check", "explain"):
            command.add_argument("--question", required=True)
        if name == "search":
            command.add_argument(
                "--mode", choices=("bm25", "dense", "hybrid", "reranked"), default="bm25"
            )
            command.add_argument("--requires-visual-evidence", action="store_true")
        if name in ("evidence", "context"):
            command.add_argument("--evidence-id", required=True)
        if name == "context":
            command.add_argument("--radius", type=int, default=1)
        if name == "visual":
            command.add_argument("--page-index", type=int, required=True)
        if name == "page":
            command.add_argument("--page-index", required=True, type=int)
            command.add_argument("--offset", type=int, default=0)
            command.add_argument("--limit", type=int, default=5)
        if name in ("check", "explain"):
            command.add_argument("--evidence-id", action="append", default=[])
            command.add_argument(
                "--draft",
                type=Path,
                required=True,
                help="UTF-8 JSON DraftAnswer, generated by your agent",
            )
        if name in ("calculate", "recipe"):
            command.add_argument(
                "--calculation",
                type=Path,
                required=True,
                help="UTF-8 JSON source-backed CalculationRequest",
            )
    serve = commands.add_parser("mcp", help="Run the optional stdio MCP server")
    serve.add_argument(
        "--documents-root",
        type=Path,
        help="Allow ingestion only below this directory; omitted disables ingestion",
    )
    skill = commands.add_parser("export-skill", help="Export the bundled companion skill")
    skill.add_argument("destination", type=Path)
    return result


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    # Library recommendations must not corrupt stdout JSON or MCP frames.
    pymupdf.no_recommend_layout()  # type: ignore[no-untyped-call]
    try:
        if args.command == "export-skill":
            destination = export_skill(args.destination)
            print(json.dumps({"skill_directory": str(destination), "installed": False}))
            return 0
        if args.command == "mcp":
            from evidence_rag.mcp_server import serve

            serve(args.artifact_root, args.documents_root)
            return 0
        engine = EvidenceRAG(artifact_root=args.artifact_root)
        output: BaseModel
        if args.command == "ingest":
            output = engine.ingest(args.path)
        elif args.command == "documents":
            output = engine.documents(offset=args.offset, limit=args.limit)
        elif args.command == "doctor":
            output = engine.doctor()
        elif args.command in ("search-collection", "check-collection"):
            with args.request.open("rb") as stream:
                payload = stream.read(65537)
            if len(payload) > 65536:
                raise ValueError("collection request exceeds 64 KiB")
            output = (
                engine.check_collection(CollectionDraftRequest.model_validate_json(payload))
                if args.command == "check-collection"
                else engine.search_collection(CollectionSearchRequest.model_validate_json(payload))
            )
        else:
            document = DocumentRef(document_id=args.document_id, document_sha256=args.sha256)
            if args.command == "search":
                output = engine.search(
                    SearchRequest(
                        **document.model_dump(),
                        question=args.question,
                        mode=args.mode,
                        requires_visual_evidence=args.requires_visual_evidence,
                    )
                )
            elif args.command == "evidence":
                output = engine.evidence(document, args.evidence_id)
            elif args.command == "context":
                output = engine.context(document, args.evidence_id, radius=args.radius)
            elif args.command == "visual":
                from evidence_rag.visual import page_image

                output = page_image(engine, document, args.page_index)
            elif args.command == "retry":
                output = engine.retry(document)
            elif args.command == "status":
                output = engine.status(document)
            elif args.command == "page":
                output = engine.page_evidence(
                    document, args.page_index, offset=args.offset, limit=args.limit
                )
            elif args.command in ("calculate", "recipe"):
                with args.calculation.open("rb") as stream:
                    calculation_bytes = stream.read(8193)
                if len(calculation_bytes) > 8192:
                    raise ValueError("calculation request exceeds 8 KiB")
                output = (
                    engine.calculate_recipe(
                        document, CalculationRecipe.model_validate_json(calculation_bytes)
                    )
                    if args.command == "recipe"
                    else engine.calculate(
                        document, CalculationRequest.model_validate_json(calculation_bytes)
                    )
                )
            else:
                with args.draft.open("rb") as stream:
                    draft_bytes = stream.read(65537)
                if len(draft_bytes) > 65536:
                    raise ValueError("draft exceeds 64 KiB")
                draft = DraftAnswer.model_validate_json(draft_bytes)
                output = (
                    engine.explain_check(document, args.question, args.evidence_id, draft)
                    if args.command == "explain"
                    else engine.check_draft(document, args.question, args.evidence_id, draft)
                )
        print(output.model_dump_json())
        return int(
            isinstance(output, DocumentIngestionResponse)
            and output.state is not IngestionState.READY
        )
    except IntakeError as exc:
        print(json.dumps({"error": exc.code, "message": exc.message}), file=sys.stderr)
    except CalculationError as exc:
        print(json.dumps({"error": exc.code}), file=sys.stderr)
    except (OSError, ValueError, ValidationError, ArtifactNotFoundError, StorageError):
        print(json.dumps({"error": "invalid_request_or_artifact"}), file=sys.stderr)
    except ImportError:
        print(
            json.dumps(
                {
                    "error": "optional_dependency_missing",
                    "message": "Install MCP requirements; see docs/agent_integration.md.",
                }
            ),
            file=sys.stderr,
        )
    return 1


if __name__ == "__main__":
    sys.exit(main())
