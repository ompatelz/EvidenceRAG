"""JSON command-line interface to the provider-free local SDK."""

import argparse
import json
import sys
from importlib.resources import files
from pathlib import Path

import pymupdf
from pydantic import BaseModel, ValidationError

from evidence_rag import __version__
from evidence_rag.answers import DraftAnswer
from evidence_rag.config import AppSettings
from evidence_rag.documents import IntakeError
from evidence_rag.documents.storage import ArtifactNotFoundError, StorageError
from evidence_rag.sdk import DocumentRef, EvidenceRAG, SearchRequest


def export_skill(destination: Path) -> Path:
    """Export the bundled skill to a new directory; never overwrite an installation."""
    source = files("evidence_rag").joinpath("evidence-rag-agent")
    destination.mkdir(parents=True, exist_ok=False)
    for relative in ("SKILL.md", "agents/openai.yaml", "references/tools.md"):
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(source.joinpath(relative).read_bytes())
    return destination


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(prog="evidence-rag")
    result.add_argument("--version", action="version", version=__version__)
    result.add_argument("--artifact-root", type=Path, default=Path("artifacts"))
    commands = result.add_subparsers(dest="command", required=True)
    ingest = commands.add_parser("ingest", help="Ingest an explicitly selected local PDF")
    ingest.add_argument("path", type=Path)
    for name in ("search", "evidence", "check", "retry"):
        command = commands.add_parser(name)
        command.add_argument("--document-id", required=True)
        command.add_argument("--sha256", required=True)
        if name in ("search", "check"):
            command.add_argument("--question", required=True)
        if name == "search":
            command.add_argument(
                "--mode", choices=("bm25", "dense", "hybrid", "reranked"), default="bm25"
            )
            command.add_argument("--requires-visual-evidence", action="store_true")
        if name == "evidence":
            command.add_argument("--evidence-id", required=True)
        if name == "check":
            command.add_argument("--evidence-id", action="append", required=True)
            command.add_argument(
                "--draft",
                type=Path,
                required=True,
                help="UTF-8 JSON DraftAnswer, generated by your agent",
            )
    serve = commands.add_parser("mcp", help="Run the optional stdio MCP server")
    serve.add_argument(
        "--documents-root",
        type=Path,
        help="Allow ingestion only below this directory; omitted disables ingestion",
    )
    skill = commands.add_parser("export-skill", help="Export the bundled companion skill")
    skill.add_argument("destination", type=Path)
    return result


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    # Library recommendations must not corrupt stdout JSON or MCP frames.
    pymupdf.no_recommend_layout()  # type: ignore[no-untyped-call]
    try:
        if args.command == "export-skill":
            destination = export_skill(args.destination)
            print(json.dumps({"skill_directory": str(destination), "installed": False}))
            return 0
        if args.command == "mcp":
            from evidence_rag.mcp_server import serve

            serve(args.artifact_root, args.documents_root)
            return 0
        engine = EvidenceRAG(settings=AppSettings(artifact_root=args.artifact_root))
        output: BaseModel
        if args.command == "ingest":
            output = engine.ingest(args.path)
        else:
            document = DocumentRef(document_id=args.document_id, document_sha256=args.sha256)
            if args.command == "search":
                output = engine.search(
                    SearchRequest(
                        **document.model_dump(),
                        question=args.question,
                        mode=args.mode,
                        requires_visual_evidence=args.requires_visual_evidence,
                    )
                )
            elif args.command == "evidence":
                output = engine.evidence(document, args.evidence_id)
            elif args.command == "retry":
                output = engine.retry(document)
            else:
                draft = DraftAnswer.model_validate_json(args.draft.read_bytes())
                output = engine.check_draft(document, args.question, args.evidence_id, draft)
        print(output.model_dump_json())
        return 0
    except IntakeError as exc:
        print(json.dumps({"error": exc.code, "message": exc.message}), file=sys.stderr)
    except (OSError, ValueError, ValidationError, ArtifactNotFoundError, StorageError):
        print(json.dumps({"error": "invalid_request_or_artifact"}), file=sys.stderr)
    except ImportError:
        print(
            json.dumps(
                {
                    "error": "optional_dependency_missing",
                    "message": "Install MCP requirements; see docs/agent_integration.md.",
                }
            ),
            file=sys.stderr,
        )
    return 1


if __name__ == "__main__":
    sys.exit(main())
